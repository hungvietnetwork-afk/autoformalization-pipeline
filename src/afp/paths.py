"""Every path the pipeline reads or writes, in one place.

ROOT is the repository folder (the one holding pyproject.toml); set AFP_ROOT to override.
Layout (course guide, section 4):

  data/           full datasets are rebuilt by scripts (not versioned); tiers/ and the candidate store are
  data_sample/    small legal sample, enough to run the pipeline end to end without downloading anything
  results/raw/    raw results: one folder per run (runs/<run_id>/) plus per-run rows and raw measurements
  results/figures tables and figures generated by scripts from results/raw
  audit/          semantic audit set (frozen sample, rater sheets, labels)
"""
from __future__ import annotations

import os


def _find_root() -> str:
    env = os.environ.get("AFP_ROOT")
    if env:
        return os.path.abspath(env)
    d = os.path.dirname(os.path.abspath(__file__))
    for _ in range(6):
        if os.path.exists(os.path.join(d, "pyproject.toml")):
            return d
        d = os.path.dirname(d)
    return os.getcwd()


ROOT = _find_root()
DATA = os.path.join(ROOT, "data")
DATA_SAMPLE = os.path.join(ROOT, "data_sample")
TIERS_DIR = os.path.join(DATA, "tiers")
CANDIDATES_DB = os.path.join(DATA, "candidates.db")
_FULL_UNITS = os.path.join(DATA, "units", "all_units.jsonl")
# Without the full download, fall back to the versioned 100-problem sample (tier T100 runs end to end).
UNITS = _FULL_UNITS if os.path.exists(_FULL_UNITS) else os.path.join(DATA_SAMPLE, "units_T100.jsonl")
CORPUS_JSONL = os.path.join(DATA, "formalized_corpus.jsonl")
CORPUS_PARQUET = os.path.join(DATA, "lake", "formalized")

RESULTS = os.path.join(ROOT, "results")
RAW = os.path.join(RESULTS, "raw")
RUNS = os.path.join(RAW, "runs")
TABLES = os.path.join(RESULTS, "figures")      # script-generated tables live next to the figures
FIG = TABLES
AUDIT = os.path.join(ROOT, "audit")
CONFIGS = os.path.join(ROOT, "configs")


def result_path(name: str) -> str:
    """Locate a result file by name: results/figures first, then results/raw."""
    for d in (TABLES, RAW):
        p = os.path.join(d, name)
        if os.path.exists(p):
            return p
    return os.path.join(TABLES, name)


def run_dir(run: str) -> str:
    """Accept a run id, a 'runs/<id>' path from older docs, or any existing directory."""
    if os.path.isdir(run):
        return os.path.abspath(run)
    name = os.path.basename(run.rstrip("/"))
    return os.path.join(RUNS, name)
