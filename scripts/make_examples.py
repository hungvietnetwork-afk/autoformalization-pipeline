"""docs/EXAMPLES_20.md: the 20 worked examples of the specification (guide, group 5, week 1: "20 examples").

The 20 problems are the stratified subset T20 used for the one-problem-per-request baseline
(data/jobs/v1_zeroshot_1req/SUBSET_20.json). For each problem: the natural-language statement, the Lean statement
generated by the baseline (zero-shot, one request), the Lean status and the automatic semantic verdict.
Everything is read from data/ and results/raw/; nothing is typed by hand.

    python scripts/make_examples.py            (AFP_ROOT=<repo> to read another checkout)
"""
from __future__ import annotations

import csv
import json
import os
import sqlite3
import sys

ROOT = os.environ.get("AFP_ROOT") or os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))

from afp.paths import CANDIDATES_DB, RUNS, UNITS  # noqa: E402
from afp.inference.batchfile import load_units  # noqa: E402

RUN = "base_T20_1req_A"
VERDICT = {"EQUIV_GOLD": "tương đương gold (Lean chứng minh)", "PROVED_CONSISTENT": "Lean suy ra đáp án từ giả thiết",
           "NO_EVIDENCE_OF_ERROR": "không thấy lỗi", "ANSWER_MISSING": "cờ: thiếu đáp án",
           "ARITHMETIC_ONLY": "cờ: chỉ còn phép tính", "TRIVIAL": "cờ: tầm thường", "FALSE": "cờ: bị phản chứng",
           "VACUOUS": "cờ: giả thiết mâu thuẫn"}


def main() -> None:
    subset = json.load(open(os.path.join(ROOT, "data/jobs/v1_zeroshot_1req/SUBSET_20.json"), encoding="utf-8"))
    units = load_units(UNITS)
    con = sqlite3.connect(CANDIDATES_DB)
    rows = {r["problem_id"]: r for r in csv.DictReader(open(os.path.join(RUNS, RUN, "raw_results.csv"), encoding="utf-8"))}
    sem = {d["task_hash"]: d for d in map(json.loads, open(os.path.join(RUNS, RUN, "semantic.jsonl"), encoding="utf-8"))}
    out = ["# 20 ví dụ NL → Lean (đặc tả tuần 1)", "",
           "Hai mươi bài của tập con cố định T20 (lấy theo nguồn, thứ tự SHA-256 của `problem_id`; quy tắc trong "
           "`data/jobs/v1_zeroshot_1req/SUBSET_20.json`). Phát biểu Lean là output của baseline bắt buộc: zero-shot, một bài mỗi "
           f"request, một ứng viên (prompt `v1_zeroshot_1req`, mô hình Claude Haiku 5.5). Trạng thái Lean và kết luận ngữ nghĩa lấy từ lần chạy `{RUN}`.",
           "", "File này được sinh bằng `python scripts/make_examples.py`; không sửa tay.", ""]
    for i, pid in enumerate(subset["problem_ids"], 1):
        u = units[pid]
        r = rows.get(pid) or {}
        code = con.execute("SELECT lean_code FROM candidates WHERE problem_id=? AND prompt_version='v1_zeroshot_1req'",
                           (pid,)).fetchone()
        s = sem.get(r.get("task_hash", ""), {})
        stmt = u.natural_statement.strip()
        out += [f"## {i}. `{pid}`", "",
                f"Nguồn {u.source}, lĩnh vực {u.domain}. Lean: **{r.get('status', 'chưa chạy')}**"
                f" ({float(r.get('latency_ms') or 0):.0f} ms). Kết luận tự động: **{VERDICT.get(s.get('verdict'), s.get('verdict') or 'chưa kiểm')}**.",
                "", "> " + stmt.replace("\n", "\n> "), "", "```lean", (code[0] if code else "-- không có ứng viên").strip(), "```", ""]
    path = os.path.join(ROOT, "docs", "EXAMPLES_20.md")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    print("wrote", path, len(subset["problem_ids"]), "examples")


if __name__ == "__main__":
    main()
